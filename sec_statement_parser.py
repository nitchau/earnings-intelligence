def extract_prose_revenue_claims(text: str, max_chars: int = 5000) -> dict:
    """Pull the headline revenue growth % and amount from the opening of the release."""
    head = flatten(text)[:max_chars]
    pat = (r"(?<![A-Za-z])(?:Total\s+|Consolidated\s+(?:\w+\s+)?)?(?:revenues?|net\s+sales)\s+"
           r"(?:of\s+\$[\d.,]+\s+(?:billion|million)\s*,?\s*)?"
           r"(?:increased|grew|rose|was\s+up|up|growth\s+of)\s+(\d+(?:\.\d+)?)%"
           r"(?:\s+year[\s-]+over[\s-]+year)?(?:\s+to\s+\$([\d.,]+)\s+(billion|million))?")
    for m in re.finditer(pat, head, re.IGNORECASE):
        pre = head[max(0, m.start() - 25):m.start()]
        if re.search(r"(Subscription|Product|Service|Services|Cloud|Segment|Advertising|Organic)\s*$", pre, re.IGNORECASE):
            continue
        amt = None
        if m.group(2):
            amt = float(m.group(2).replace(",", "")) * (1000.0 if m.group(3).lower() == "billion" else 1.0)
        return {"stated_yoy_pct": float(m.group(1)), "stated_amount_millions": amt, "snippet": m.group(0)}
    return {}


def extract_reported_quarter_end_dates(text: str, earnings_date: str, max_chars: int = 25000) -> list[str]:
    """Dates of the form 'Month DD, YYYY' or split table headers
    'Three Months Ended Month DD, ... YYYY' that fall 10-95 days before release."""
    head = flatten(text)[:max_chars]
    ed = date.fromisoformat(earnings_date)
    out = []

    for m in re.finditer(rf"({MONTHS})\s+(\d{{1,2}}),\s+(20\d\d)", head, re.IGNORECASE):
        try:
            d = datetime.strptime(f"{m.group(1).title()} {m.group(2)} {m.group(3)}", "%B %d %Y").date()
        except ValueError:
            continue
        if 10 <= (ed - d).days <= 95:
            out.append(d.isoformat())

    # Also support split-year table headers: "Three Months Ended September 30, Nine Months Ended September 30, 2026"
    if not out:
        for m in re.finditer(
            rf"(?:Three\s+Months|Quarter)\s+Ended\s+({MONTHS})\s+(\d{{1,2}}),?(?:[^0-9]{{0,80}})?\b(20\d\d)\b",
            head,
            re.IGNORECASE,
        ):
            try:
                d = datetime.strptime(f"{m.group(1).title()} {m.group(2)} {m.group(3)}", "%B %d %Y").date()
            except ValueError:
                continue
            if 10 <= (ed - d).days <= 95:
                out.append(d.isoformat())

    return sorted(set(out))
