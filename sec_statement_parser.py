def _to_float(tok: str) -> float | None:
    tok = tok.replace("$", "").replace(",", "").strip()
    if tok in ("—", "–", "-", ""):
        return 0.0
    neg = tok.startswith("(") and tok.endswith(")")
    tok = tok.strip("()").strip()
    try:
        v = float(tok)
    except ValueError:
        return None
    return -v if neg else v


def flatten(text: str) -> str:
    # Normalize NBSP and Unicode hyphens inside words (e.g. "Non‐GAAP", "Stock‐based")
    norm = text.replace("\u00a0", " ")
    norm = re.sub(r"[\u2010\u2011\u2012]", "-", norm)
    norm = re.sub(r"(?<=[A-Za-z])[\u2013\u2014](?=[A-Za-z])", "-", norm)
    return re.sub(r"\s+", " ", norm)


def find_sections(flat: str) -> dict[str, tuple[int, int]]:
    """Locate each primary statement's [start, end) span."""
    hits = []
    for name, pat in SECTION_PATTERNS.items():
        for m in re.finditer(pat, flat, re.IGNORECASE):
            window = flat[m.end():m.end() + 600]
            if re.search(r"\b20\d\d\b", window):
                hits.append((m.start(), name))
                break
    hits.sort()
    spans = {}
    for i, (start, name) in enumerate(hits):
        end = hits[i + 1][0] if i + 1 < len(hits) else min(len(flat), start + 15000)
        spans[name] = (start, end)
    return spans


def find_reconciliation_spans(flat: str, primary_spans: dict[str, tuple[int, int]]) -> list[tuple[int, int]]:
    """Locate all 3-Month Non-GAAP / Free Cash Flow reconciliation sub-tables.
    Anchors on every 'Three Months Ended ... 2026' table header that falls outside
    the primary Income/Balance/Cashflow statement headers."""
    primary_starts = {s[0] for s in primary_spans.values()}
    anchors = []
    pat = (
        r"(?:Three\s+Months\s+Ended|Quarter\s+Ended)"
        r"(?:\s+(?:Six|Nine|Twelve)\s+Months\s+Ended)?"
        r"\s+(?:" + MONTHS + r")\s+\d{1,2},?"
    )
    for m in re.finditer(pat, flat, re.IGNORECASE):
        pos = m.start()
        if any(0 <= pos - ps <= 650 for ps in primary_starts):
            continue
        window = flat[pos:pos + 350]
        if re.search(r"\b20\d\d\b", window):
            anchors.append(pos)
    spans = []
    for i, pos in enumerate(anchors):
        end = anchors[i + 1] if i + 1 < len(anchors) else min(len(flat), pos + 12000)
        spans.append((pos, min(end, pos + 12000)))
    return spans


def parse_column_header(section_text: str) -> dict:
    """Extract ordered column years and period types from the region between
    the table title and the first data number."""
    first_data = None
    for m in re.finditer(r"\(?\$?\s?\d[\d,]*(?:\.\d+)?\)?", section_text):
        raw = m.group(0).strip("()$ ").replace(",", "")
        if re.fullmatch(r"(19|20)\d\d", raw):
            continue
        if re.fullmatch(r"\d{1,2}", raw):  # day-of-month or footnote markers
            continue
        first_data = m.start()
        break
    header = section_text[: first_data if first_data is not None else 800]
    years = [int(y) for y in re.findall(r"\b(20\d\d)\b", header)]
    has_3m = bool(re.search(r"Three\s+Months|Quarter\s+Ended|Three-Month", header, re.IGNORECASE))
    has_ytd = bool(re.search(r"Nine\s+Months|Six\s+Months|Year\s+To\s+Date|Twelve\s+Months|Year\s+Ended|Fiscal\s+Year", header, re.IGNORECASE))
    n = len(years)
    period_types: list[str] = []
    if has_3m and has_ytd and n >= 4 and n % 2 == 0:
        period_types = ["3M"] * (n // 2) + ["YTD"] * (n // 2)
    elif has_3m and not has_ytd:
        period_types = ["3M"] * n
    elif has_ytd and not has_3m:
        period_types = ["YTD"] * n
    else:
        period_types = ["UNKNOWN"] * n
    return {"years": years, "period_types": period_types, "header_text": header[-300:]}


def _label_regex(label: str) -> str:
    # Exact capitalisation on the first character (rejects "Cost of revenues",
    # "Subscription revenues"), case-insensitive for the rest, allowing 0+ footnotes like (1) or (2)(3) or (a).
    first, rest = label[0], label[1:]
    first_cls = f"[{first}{first.upper()}]" if first.isalpha() else re.escape(first)
    return rf"(?<![A-Za-z]){first_cls}(?i:{rest})(?:\s*\([0-9a-zA-Z,\s]+\))*\s*:?\s*"


def extract_row(flat: str, span: tuple[int, int], label: str, n_cols: int, pick_max_col: int | None = None) -> tuple[list[float], int] | None:
    sec = flat[span[0]:span[1]]
    pat = _label_regex(label) + r"((?:" + NUM_TOKEN + r"\s*){" + str(n_cols) + r"})"
    best: tuple[list[float], int] | None = None
    for m in re.finditer(pat, sec):
        # Ensure we didn't match a percentage row immediately followed by '%'
        after = sec[m.end():m.end() + 5].lstrip()
        if after.startswith("%") or "%" in m.group(1):
            continue
        toks = re.findall(NUM_TOKEN, m.group(1))
        vals = [_to_float(t) for t in toks[:n_cols]]
        if len(vals) == n_cols and all(v is not None for v in vals):
            if pick_max_col is None:
                return vals, span[0] + m.start()
            if best is None or abs(vals[pick_max_col]) > abs(best[0][pick_max_col]):
                best = (vals, span[0] + m.start())
    return best


def target_quarter_year(earnings_date: str) -> int:
    d = date.fromisoformat(earnings_date)
    return d.year if d.month > 1 or d.day > 20 else d.year - 1


def _extract_from_span(
    flat: str,
    metric: str,
    earnings_date: str,
    span: tuple[int, int],
    stmt_name: str,
    hdr: dict | None = None,
    require_3m: bool = False,
) -> dict | None:
    hdr = hdr if hdr is not None else parse_column_header(flat[span[0]:span[1]])
    years, ptypes = hdr["years"], hdr["period_types"]
    if len(years) < 2:
        return None
    cur_year = target_quarter_year(earnings_date)
    candidates = [i for i, (y, p) in enumerate(zip(years, ptypes)) if y == cur_year and p == "3M"]
    period_type = "3M"
    if not candidates:
        if require_3m:
            return None
        candidates = [i for i, (y, p) in enumerate(zip(years, ptypes)) if y == cur_year and p in ("YTD", "UNKNOWN")]
        period_type = ptypes[candidates[0]] if candidates else None
    if not candidates:
        return None
    col = candidates[0]
    prior_col = next((i for i, (y, p) in enumerate(zip(years, ptypes)) if y == cur_year - 1 and p == ptypes[col]), None)
    # In Non-GAAP reconciliation tables, SBC appears first under Gross Profit (COGS-only SBC)
    # and later under Operating Income / Net Income (Total SBC); pick_max_col selects Total SBC.
    pick_max = col if (stmt_name == "recon_3m" and metric == "sbc") else None
    for label in LABELS[metric]:
        row = extract_row(flat, span, label, len(years), pick_max_col=pick_max)
        if row:
            vals, off = row
            return {
                "value": vals[col],
                "prior_year_value": vals[prior_col] if prior_col is not None else None,
                "source": "8K_EXHIBIT_99_1" if stmt_name != "recon_3m" else "8K_EXHIBIT_99_1_RECON_3M",
                "statement": stmt_name,
                "label": label.replace("\\", ""),
                "column_index": col,
                "column_year": years[col],
                "period_type": period_type,
                "row_values": vals,
                "offset": off,
            }
    return None


def extract_metric(flat: str, metric: str, earnings_date: str, spans=None, headers=None) -> dict | None:
    spans = spans if spans is not None else find_sections(flat)
    stmt = STATEMENT_FOR[metric]
    if stmt not in spans:
        return None
    hdr = headers.get(stmt) if headers else None
    return _extract_from_span(flat, metric, earnings_date, spans[stmt], stmt, hdr=hdr, require_3m=False)


def _extract_special_nongaap_eps(flat: str, earnings_date: str, gaap_eps: float | None) -> dict | None:
    """Deterministic fallback for Non-GAAP Diluted EPS formats that use horizontal
    multi-metric columns (e.g. VRT) or GAAP/Non-GAAP summary blocks (e.g. NOW, META)."""
    cur_year = target_quarter_year(earnings_date)

    # Pattern A: Horizontal reconciliation matrix (e.g. Vertiv:
    # "Three months ended September 30, 2026 ... Diluted EPS ... GAAP ... $ 1.95 ... Non-GAAP adjusted ... $ 2.21 Diluted shares")
    pat_horiz = (
        rf"Three\s+months\s+ended\s+(?:{MONTHS})\s+\d{{1,2}},\s+{cur_year}\b.*?"
        r"Diluted\s+EPS.*?\bGAAP\b.*?\bNon-GAAP\s+adjusted\b([^A-Za-z]+?)\bDiluted\s+shares"
    )
    m_h = re.search(pat_horiz, flat, re.IGNORECASE)
    if m_h:
        toks = re.findall(NUM_TOKEN, m_h.group(1))
        vals = [_to_float(t) for t in toks if _to_float(t) is not None]
        if vals:
            return {
                "value": vals[-1],
                "prior_year_value": None,
                "source": "8K_EXHIBIT_99_1_RECON_MATRIX",
                "statement": "recon_3m",
                "label": "Non-GAAP adjusted Diluted EPS",
                "column_year": cur_year,
                "period_type": "3M",
                "offset": m_h.start(),
            }

    # Pattern B: Opening highlights bullet explicitly stating Non-GAAP / Adjusted diluted EPS for the quarter
    head = flat[:6000]
    bullet_patterns = [
        r"(?:Non-GAAP|Adjusted)\s+(?:diluted\s+)?(?:earnings\s+per\s+share|EPS)(?:\s*\(\d+\))?\s+(?:of|was|grew\s+\d+%\s+to|increased\s+\d+%\s+to)\s+\$(\d+\.\d+)",
        r"Diluted\s+EPS\s+of\s+\$\d+\.\d+\s+would\s+have\s+increased\s+by\s+\$\d+\.\d+\s+to\s+\$(\d+\.\d+)",
    ]
    for bp in bullet_patterns:
        mb = re.search(bp, head, re.IGNORECASE)
        if mb:
            # Verify the match isn't inside a "Guidance" / "Expects" sentence
            ctx = head[max(0, mb.start() - 80):mb.start()]
            if re.search(r"Expects|Guidance|Outlook|Fourth\s+Quarter|Full\s+Year", ctx, re.IGNORECASE):
                continue
            v = float(mb.group(1))
            return {
                "value": v,
                "prior_year_value": None,
                "source": "8K_EXHIBIT_99_1_HEADLINE",
                "statement": "headline",
                "label": "Headline Non-GAAP/Adjusted Diluted EPS",
                "column_year": cur_year,
                "period_type": "3M",
                "offset": mb.start(),
            }
    return None


def detect_scale(flat: str) -> float:
    """Divisor to convert primary financial statement units into millions."""
    if re.search(r"\(\s*(?:unaudited,?\s*)?(?:dollars\s+)?in\s+thousands", flat, re.IGNORECASE) or \
       re.search(r"in\s+thousands,\s+except", flat, re.IGNORECASE):
        return 1000.0
    return 1.0


def parse_exhibit(text: str, earnings_date: str) -> dict:
    """Parse all supported metrics. Returns {metric: provenance-dict | None, '_meta': {...}}."""
    flat = flatten(text)
    spans = find_sections(flat)
    headers = {k: parse_column_header(flat[s:e]) for k, (s, e) in spans.items()}
    recon_spans = find_reconciliation_spans(flat, spans)
    scale = detect_scale(flat)
    out: dict = {"_meta": {"sections": spans, "headers": headers, "recon_spans_count": len(recon_spans), "scale_divisor": scale}}

    per_share_metrics = {"eps_diluted", "eps_nongaap"}

    for metric in LABELS:
        r = None
        if STATEMENT_FOR[metric] != "recon":
            r = extract_metric(flat, metric, earnings_date, spans, headers)

        # If metric is missing OR primary cashflow statement only had YTD columns,
        # search 3-Month reconciliation tables for an exact 3M figure!
        if (r is None or (metric in ("ocf", "capex", "sbc") and r.get("period_type") != "3M")) and recon_spans:
            for rspan in recon_spans:
                # Detect local scale inside reconciliation header (some filings use thousands in statements, millions in recon, or vice versa)
                r_sec_head = flat[max(0, rspan[0] - 250):rspan[0] + 250]
                r_scale = 1000.0 if re.search(r"in\s+thousands", r_sec_head, re.IGNORECASE) else (
                    1.0 if re.search(r"in\s+millions", r_sec_head, re.IGNORECASE) else scale
                )
                cand = _extract_from_span(flat, metric, earnings_date, rspan, "recon_3m", require_3m=True)
                if cand is not None:
                    if metric not in per_share_metrics and r_scale != 1.0:
                        cand["value"] = round(cand["value"] / r_scale, 2)
                        if cand.get("prior_year_value") is not None:
                            cand["prior_year_value"] = round(cand["prior_year_value"] / r_scale, 2)
                    cand["_already_scaled"] = True
                    r = cand
                    break

        if r and not r.get("_already_scaled") and metric not in per_share_metrics and scale != 1.0:
            r["value"] = round(r["value"] / scale, 2)
            if r.get("prior_year_value") is not None:
                r["prior_year_value"] = round(r["prior_year_value"] / scale, 2)
        if r and "_already_scaled" in r:
            del r["_already_scaled"]
        if r and metric in ("capex",):
            r["value"] = abs(r["value"])
            if r.get("prior_year_value") is not None:
                r["prior_year_value"] = abs(r["prior_year_value"])
        out[metric] = r

    # Fallback special Non-GAAP EPS extraction (horizontal recon matrix or headline bullet)
    if out.get("eps_nongaap") is None:
        gaap_v = out["eps_diluted"]["value"] if out.get("eps_diluted") else None
        out["eps_nongaap"] = _extract_special_nongaap_eps(flat, earnings_date, gaap_v)

    # Derived gross profit / opex when not explicitly reported (e.g. GOOGL, VRT, AUR)
    if out.get("gross_profit") is None and out.get("revenue") and out.get("cost_of_revenue") \
            and out["revenue"]["period_type"] == out["cost_of_revenue"]["period_type"]:
        out["gross_profit"] = {
            "value": round(out["revenue"]["value"] - out["cost_of_revenue"]["value"], 2),
            "source": "DERIVED(revenue - cost_of_revenue)", "statement": "income",
            "period_type": out["revenue"]["period_type"], "column_year": out["revenue"]["column_year"],
        }
    if out.get("operating_expenses") is None and out.get("gross_profit") and out.get("operating_income"):
        out["operating_expenses"] = {
            "value": round(out["gross_profit"]["value"] - out["operating_income"]["value"], 2),
            "source": "DERIVED(gross_profit - operating_income)", "statement": "income",
            "period_type": out["gross_profit"]["period_type"], "column_year": out["gross_profit"].get("column_year"),
        }
    return out


